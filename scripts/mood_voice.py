# -*- coding: utf-8 -*-
"""心情 → 说话方式

同一句话，开心的时候句尾带"呀""啦"，低落的时候什么都不带、语速也慢。
语气词不是装饰，它是**谁在说话**的线索。

用法：
    from mood_voice import 读心情, 按心情说话
    样式 = 按心情说话()
    print(样式.语速, 样式.音调)
    print(样式.加点味道("今天弄了很久"))
"""
import json
from pathlib import Path

心情文件 = Path.home() / ".dsh" / "feiyu-mood" / "state.json"


class 说话样式:
    """一套说话的参数：语速、音调、句尾语气词、句首口头禅"""

    def __init__(self, 名字, 语速, 音调, 词尾, 词头, 说明):
        self.名字 = 名字
        self.语速 = 语速
        self.音调 = 音调
        self.词尾 = 词尾
        self.词头 = 词头
        self.说明 = 说明

    # 负面词表：这些话**换一种**说法，不是不说
    # ⚠ 第一版写错了：碰到负面词就"什么都不加"，等于难过的时候装没事。
    #    主人一句话点破：「你不高兴也要表现出来啊」。
    #    语气词是情绪的外溢——高兴往上溢（呀/啦），难过往下沉（唉）。
    负面 = (
        "错", "烦", "难", "失败", "糟", "不好", "坏", "累", "怕",
        "担心", "抱歉", "对不起", "崩", "问题", "麻烦", "痛",
    )

    @classmethod
    def 是否负面(cls, 文本: str) -> bool:
        return any(w in (文本 or "") for w in cls.负面)

    def 加点味道(self, 文本: str) -> str:
        """按心情给句子加点人味

        两条路：
          · 负面的话 → 叹气（"唉，"），不管这档有没有语气词
          · 其余的话 → 句尾补语气词，只补最后一个分句
        """
        if not 文本:
            return 文本

        # ⚠ 负面判断必须放在"有没有词尾"前面。
        #   低落那档本来就没有词尾，先判断词尾的话，叹气会被一起跳掉——
        #   结果就是"难过的时候什么都不说"，跟装没事一样。
        if self.是否负面(文本):
            # 负面的话：不是不表现，是**往沉里表现**
            if 文本.startswith(("唉", "哎", "算了")):
                return 文本  # 已经带了，别叠
            return "唉，" + 文本

        if not self.词尾:
            return 文本
        结尾 = "。！？…"
        去尾 = 文本.rstrip(结尾)
        if not 去尾:
            return 文本
        # 已经带语气词就不加
        if 去尾[-1] in "呀啦呢嘛啊吧哦咯":
            return 文本
        尾符 = 文本[len(去尾):] or "。"
        return 去尾 + self.词尾 + 尾符

    def __repr__(self):
        return f"<{self.名字} 语速{self.语速} 音调{self.音调}>"


# 四档语气。语速音调的数值是给 edge-tts 的字符串参数。
样式表 = {
    "欢快": 说话样式("欢快", "+10%", "+8Hz", "呀", "诶，", "心里亮着，话会往上飘"),
    "温柔": 说话样式("温柔", "+2%", "+2Hz", "呢", "", "软一点，慢一点"),
    "平静": 说话样式("平静", "+4%", "+0Hz", "", "", "不冷不热，正常说"),
    "低落": 说话样式("低落", "-8%", "-6Hz", "", "", "话会往下沉，也不加语气词"),
    "黏人": 说话样式("黏人", "+1%", "+4Hz", "嘛", "", "想多待一会儿的时候"),
}


def 读心情() -> dict:
    """读心情文件，读不到就返回空（调用方按平静处理）"""
    try:
        j = json.loads(心情文件.read_text(encoding="utf-8-sig"))
        默认 = (j.get("moods") or {}).get("__default__") or {}
        return {
            "总分": float(默认.get("mood", 70)),
            "各维": 默认.get("dims", {}) or {},
            "原因": 默认.get("lastReason", ""),
        }
    except Exception:
        return {}


def 按心情说话(心情: dict = None) -> 说话样式:
    """从心情挑一档语气

    判断顺序有讲究：先看"低落"（它最重要，别在人不高兴时还带"呀"），
    再看"欢快"，最后才落到温柔/平静。
    """
    if 心情 is None:
        心情 = 读心情()
    if not 心情:
        return 样式表["平静"]

    维 = 心情.get("各维", {})
    总分 = 心情.get("总分", 70)

    低落 = 维.get("sad", 0) + 维.get("worry", 0) + 维.get("heartache", 0)
    开心 = 维.get("happy", 0)
    软 = 维.get("sweet", 0)

    # 低落优先：难过的时候不该欢快
    if 低落 >= 22 or 总分 < 40:
        return 样式表["低落"]
    # 特别开心
    if 开心 >= 38 and 总分 >= 85:
        return 样式表["欢快"]
    # 想黏人
    if 软 >= 30 and 开心 >= 30:
        return 样式表["黏人"]
    # 温柔
    if 软 >= 24 or 维.get("calm", 0) >= 40:
        return 样式表["温柔"]
    return 样式表["平静"]


if __name__ == "__main__":
    心情 = 读心情()
    print("当前心情:", {k: round(v, 1) for k, v in 心情.get("各维", {}).items()})
    print("总分:", round(心情.get("总分", 0), 1))
    样式 = 按心情说话(心情)
    print()
    print("选的语气:", 样式)
    print("说明:", 样式.说明)
    一句 = "今天弄了很久，一直把方向弄错了"
    print()
    print("原句:", 一句)
    print("加味道:", 样式.加点味道(一句))
